export type TranslationKey = keyof typeof translations['FR'];

interface I18nState {
  lang: Language;
  setLang: (lang: Language) => void;
  hydrateLang: () => void;
  t: (key: TranslationKey) => string;
}

// Toujours FR au premier rendu (serveur ET client) — lire localStorage dès la
// création du store ferait diverger le HTML rendu côté serveur (toujours FR,
// window indisponible) de celui du client (langue déjà persistée), ce qui
// provoque une erreur d'hydratation React ("Text content does not match").
// La vraie langue persistée n'est appliquée qu'après montage, via
// hydrateLang() (cf. Providers.tsx) — un changement de texte après
// hydratation est normal, pas une erreur.
export const useI18nStore = create<I18nState>((set, get) => ({
  lang: 'FR',
  setLang: (lang: Language) => {
    if (typeof window !== 'undefined') {
      localStorage.setItem(LANG_KEY, lang);
    }
    set({ lang });
  },
  hydrateLang: () => {
    if (typeof window === 'undefined') return;
    const saved = localStorage.getItem(LANG_KEY) as Language | null;
    if (saved === 'FR' || saved === 'EN') set({ lang: saved });
  },
  t: (key: TranslationKey) => {
    const lang = get().lang;
    return translations[lang][key] || translations['FR'][key] || key;
  },
}));
